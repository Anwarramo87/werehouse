import {
  ArrayMinSize,
  IsArray,
  IsDateString,
  IsEnum,
  IsInt,
  IsNotEmpty,
  IsNumber,
  IsOptional,
  IsString,
  IsUUID,
  MaxLength,
  Min,
  ValidateNested,
} from 'class-validator';
import { Type } from 'class-transformer';
import { ProductionStageStatus, ProductionStageType } from '@prisma/client';

/**
 * A size/colour combination inside a production batch.
 *
 * The brief requires a batch to support several sizes and colours, each with
 * its own quantity. Storing them as rows (not a JSON blob) is what makes it
 * possible to move a quantity from one stage to the next without losing
 * track of which colour and size it was.
 */
export class BatchVariantDto {
  /** اللون */
  @IsString()
  @IsNotEmpty()
  @MaxLength(60)
  color: string;

  /** المقاس */
  @IsString()
  @IsNotEmpty()
  @MaxLength(40)
  size: string;

  /** الكمية المطلوبة */
  @IsInt()
  @Min(0)
  quantity: number;
}

/**
 * إنشاء دفعة إنتاج.
 *
 * The batch number is generated by the server (auto-incrementing, per
 * factory) — a client-supplied number would collide the first time two people
 * create a batch on the same day.
 */
export class CreateProductionBatchDto {
  /** اسم الدفعة */
  @IsString()
  @IsNotEmpty()
  @MaxLength(120)
  name: string;

  /** المنتج (SKU) — جينز، فستان، بدلة … */
  @IsString()
  @IsNotEmpty()
  @MaxLength(64)
  productSku: string;

  /** نوع المنتج: jeans | dress | suit | shirt | other */
  @IsOptional()
  @IsString()
  @MaxLength(40)
  productType?: string;

  /** تاريخ الإنشاء — يملأه الخادم إن لم يُحدَّد */
  @IsOptional()
  @IsDateString()
  createdDate?: string;

  /** الكمية الإجمالية المطلوبة */
  @IsInt()
  @Min(1)
  totalQty: number;

  /** تركيبات المقاسات والألوان — كل تركيبة لها كميتها المستقلة */
  @IsOptional()
  @IsArray()
  @ValidateNested({ each: true })
  @Type(() => BatchVariantDto)
  variants?: BatchVariantDto[];

  /** BOM المستخدمة (اختياري — يمكن ربطها لاحقاً) */
  @IsOptional()
  @IsUUID()
  bomId?: string;

  /** ملاحظات */
  @IsOptional()
  @IsString()
  @MaxLength(1000)
  notes?: string;
}

/** تسجيل استلام دفعة في مرحلة — بدء المرحلة. */
export class StartStageDto {
  /** المسؤول عن المرحلة */
  @IsOptional()
  @IsUUID()
  responsibleId?: string;

  /** الكمية المستلمة في هذه المرحلة */
  @IsInt()
  @Min(0)
  inputQty: number;

  @IsOptional()
  @IsString()
  @MaxLength(1000)
  notes?: string;
}

/** إنجاز مرحلة — تسجيل المخرجات والهدر والعيوب. */
export class CompleteStageDto {
  /** الكمية المنتجة/الصالحة */
  @IsInt()
  @Min(0)
  outputQty: number;

  /** الكمية الهالفة */
  @IsOptional()
  @IsInt()
  @Min(0)
  wasteQty?: number;

  /** الكمية المعيبة */
  @IsOptional()
  @IsInt()
  @Min(0)
  defectiveQty?: number;

  /** ملاحظات المرحلة — مثل: الحاجة إلى عراوي أو أزرار */
  @IsOptional()
  @IsString()
  @MaxLength(1000)
  notes?: string;

  /** تكلفة المرحلة */
  @IsOptional()
  @IsNumber()
  @Min(0)
  stageCost?: number;

  /** تاريخ الإنجاز — يملأه الخادم افتراضياً */
  @IsOptional()
  @IsDateString()
  completedAt?: string;
}

/** إرجاع دفعة إلى مرحلة سابقة — عملية موثقة، لا تعديل صامت. */
export class ReturnStageDto {
  /** المرحلة التي نرجع إليها */
  @IsEnum(ProductionStageType)
  stageType: ProductionStageType;

  /** سبب الإرجاع — إلزامي، لأن الإرجاع عملية موثقة */
  @IsString()
  @IsNotEmpty()
  @MaxLength(500)
  reason: string;
}


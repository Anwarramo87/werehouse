/** احتساب تكاليف دفعة. */
export class CalculateProductionCostDto {
  /** تكلفة مباشرة إضافية (أجور، طاقة …) */
  @IsOptional()
  @IsNumber()
  @Min(0)
  directCost?: number;

  /** تكاليف إضافية مشتركة تُوزَّع على الدفعة */
  @IsOptional()
  @IsNumber()
  @Min(0)
  overheadCost?: number;

  /** العملة الأصلية للتكاليف */
  @IsOptional()
  @IsString()
  @MaxLength(8)
  currency?: string;

  /** سعر الصرف المستخدم */
  @IsOptional()
  @IsNumber()
  @Min(0.0001)
  exchangeRate?: number;

  /** تاريخ سعر الصرف */
  @IsOptional()
  @IsDateString()
  exchangeRateDate?: string;
}
